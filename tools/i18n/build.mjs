// Builds docs/js/lang/<code>.js from the translation sources tools/i18n/src/<code>*.txt
// (one "id<TAB>text" per line, ids from docs/js/lang/keys.js), then checks every language:
// missing ids, unknown ids and {placeholders} that don't match the English text.
//
//   node tools/i18n/build.mjs          (all languages)
//   node tools/i18n/build.mjs fi sv    (only these)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const src = path.join(root, 'tools/i18n/src');
const out = path.join(root, 'docs/js/lang');
const { KEYS } = await import(pathToFileURL(path.join(out, 'keys.js')).href);
const ph = (s) => (s.match(/\{\w+\}/g) || []).sort().join();

const files = fs.readdirSync(src).filter(f => f.endsWith('.txt'));
const codes = [...new Set(files.map(f => f.slice(0, 2)))].filter(c => !process.argv[2] || process.argv.slice(2).includes(c));
let ok = true;
for (const code of codes.sort()) {
  const tr = {};
  for (const f of files.filter(f => f.startsWith(code)).sort()) {
    for (const [n, line] of fs.readFileSync(path.join(src, f), 'utf8').split(/\r?\n/).entries()) {
      if (!line.trim()) continue;
      const m = line.match(/^(\d+)\t(.+)$/);
      if (!m) { console.log(`${f}:${n + 1}: bad line`); ok = false; continue; }
      tr[m[1]] = m[2].trim();
    }
  }
  const unknown = Object.keys(tr).filter(id => !KEYS[id]);
  const missing = Object.keys(KEYS).filter(id => !tr[id]);
  const bad = Object.keys(tr).filter(id => KEYS[id] && ph(KEYS[id]) !== ph(tr[id]));
  if (unknown.length || bad.length) ok = false;
  console.log(`${code}: ${Object.keys(tr).length} texts, ${missing.length} missing${unknown.length ? `, unknown ids ${unknown.join(' ')}` : ''}${bad.length ? `, placeholder mismatch in ${bad.join(' ')}` : ''}`);
  const ids = Object.keys(tr).filter(id => KEYS[id]).sort((a, b) => a - b);
  fs.writeFileSync(path.join(out, code + '.js'), `// ${code} translations: { id: text } – ids are in keys.js. Generated by tools/i18n/build.mjs from tools/i18n/src.\nexport default {\n`
    + ids.map(id => `  ${id}: ${JSON.stringify(tr[id])},`).join('\n') + '\n};\n');
}
process.exit(ok ? 0 : 1);
