// Collects every English text the app shows and keeps docs/js/lang/keys.js up to date.
// Existing ids never change (translations refer to them); new texts get new ids at the end.
// Also lists, per language, the texts that still need a translation (tools/i18n/todo/<code>.json).
//
//   node tools/i18n/extract.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const js = path.join(root, 'docs/js');

// Minimal browser stand-ins so the data modules can be imported.
globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
globalThis.window = globalThis;
globalThis.addEventListener = () => {};

const texts = new Set();
const add = (s) => { if (typeof s === 'string' && s.trim()) texts.add(s); };
const unq = (s) => s.replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\\\/g, '\\');

// 1. t('…') and tr('…') calls in the app's code.
for (const f of fs.readdirSync(js).filter(f => f.endsWith('.js'))) {
  const src = fs.readFileSync(path.join(js, f), 'utf8');
  for (const m of src.matchAll(/\b(?:t|tr)\(\s*'((?:[^'\\]|\\.)*)'/g)) add(unq(m[1]));
}
// 2. Tour steps and drawn-animation captions.
const tour = fs.readFileSync(path.join(js, 'tour.js'), 'utf8');
for (const m of tour.matchAll(/\b(?:sec|title|text): '((?:[^'\\]|\\.)*)'/g)) add(unq(m[1]));
const anim = fs.readFileSync(path.join(js, 'anim.js'), 'utf8');
for (const m of anim.matchAll(/words: \[([^\]]*)\]/g)) for (const w of m[1].matchAll(/'((?:[^'\\]|\\.)*)'/g)) add(unq(w[1]));
// 3. Bottom tab labels.
['My Plan', 'Exercises', 'Gym', 'Timer', 'Progress', 'Profile'].forEach(add);
// 4. Built-in data: exercises, muscles, equipment, goals, …
const { walkData } = await import(pathToFileURL(path.join(js, 'localize.js')).href);
walkData((obj, k) => add(obj[k]));

// Merge into keys.js, keeping existing ids.
const keysFile = path.join(js, 'lang/keys.js');
let KEYS = {};
if (fs.existsSync(keysFile)) KEYS = (await import(pathToFileURL(keysFile).href + '?' + Date.now())).KEYS;
const known = new Set(Object.values(KEYS));
let next = Math.max(0, ...Object.keys(KEYS).map(Number)) + 1;
let added = 0;
for (const s of texts) if (!known.has(s)) { KEYS[next++] = s; added++; }
const unused = Object.entries(KEYS).filter(([, s]) => !texts.has(s)).length;
fs.writeFileSync(keysFile, '// English text of every translatable string, by id. Generated by tools/i18n/extract.mjs – ids never change.\n'
  + 'export const KEYS = {\n' + Object.entries(KEYS).map(([id, s]) => `  ${id}: ${JSON.stringify(s)},`).join('\n') + '\n};\n');
console.log(`${Object.keys(KEYS).length} texts (${added} new, ${unused} no longer used)`);

// What each language still needs.
const todoDir = path.join(root, 'tools/i18n/todo');
fs.mkdirSync(todoDir, { recursive: true });
for (const f of fs.readdirSync(path.join(js, 'lang')).filter(f => /^[a-z]{2}\.js$/.test(f))) {
  const code = f.slice(0, 2);
  const tr = (await import(pathToFileURL(path.join(js, 'lang', f)).href + '?' + Date.now())).default;
  const missing = Object.fromEntries(Object.entries(KEYS).filter(([id, s]) => texts.has(s) && !tr[id]));
  fs.writeFileSync(path.join(todoDir, code + '.json'), JSON.stringify(missing, null, 1));
  // Placeholders like {name} must survive translation.
  const bad = Object.entries(tr).filter(([id, s]) => KEYS[id] && (KEYS[id].match(/\{\w+\}/g) || []).sort().join() !== (s.match(/\{\w+\}/g) || []).sort().join());
  console.log(`${code}: ${Object.keys(missing).length} missing${bad.length ? `, ${bad.length} with wrong {placeholders}: ${bad.map(b => b[0]).join(', ')}` : ''}`);
}
